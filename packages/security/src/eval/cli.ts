import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SPECIALIST_IDS, createAnalysisGateway } from '@repopulse/analysis';
import { candidateOf, loadTriageCases, scoreModel } from '../triage/eval.js';
import { runTriage } from '../triage/run.js';
import { TRIAGE_CHECKLIST_VERSION } from '../triage/types.js';
import { loadEvalCases } from './fixtures.js';
import { renderModelEval } from './render.js';
import { MODEL_EVAL_RESULTS } from './results.generated.js';
import { evaluateSpecialists } from './run.js';
import type { EvalRole, ModelEvalFile, ModelEvalRow } from './types.js';

// Evaluates one model on every role and updates the published table.
//
//   npx tsx packages/security/src/eval/cli.ts \
//     --base-url http://localhost:1234/v1 --model <model id> \
//     [--concurrency 4] [--seed 7] [--roles security,ai_slop] [--skip-triage] \
//     [--context-window 262144]
//
// A run that hits a provider error is written (incomplete, errors listed) and
// the process exits 1 — the failure is loud, and nothing is scored from it.

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RESULTS_FILE = path.join(HERE, 'results.generated.ts');
const MD_FILE = path.resolve(HERE, '../../../../docs/MODEL_EVAL.md');

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}
const baseUrl = flag('base-url');
const model = flag('model');
if (!baseUrl || !model) {
  console.error(
    'usage: cli.ts --base-url <url> --model <id> [--concurrency N] [--seed N] [--roles a,b] [--skip-triage] [--context-window N]',
  );
  process.exit(2);
}
const concurrency = Number(flag('concurrency') ?? 4);
const seedArg = flag('seed');
const seed = seedArg === undefined ? null : Number(seedArg);
const contextWindow = flag('context-window') ? Number(flag('context-window')) : null;
const roles = (flag('roles')?.split(',') ?? [...SPECIALIST_IDS]) as EvalRole[];
const temperature = 0.1; // fixed by the Tier-2 client

const host = new URL(baseUrl);
const gateway = createAnalysisGateway({
  hosts: [
    {
      baseUrl,
      modelSlot: model,
      providerId: 1,
      name: model,
      ...(seed !== null ? { seed } : {}),
      ...(contextWindow !== null ? { contextWindow } : {}),
    },
  ],
  concurrencyCap: concurrency,
});

const started = Date.now();
const spec = await evaluateSpecialists(loadEvalCases(), {
  gateway,
  model,
  engine: `OpenAI-compatible endpoint at ${host.host}`,
  seed,
  temperature,
  roles,
  contextWindow,
  concurrency,
});

let triage: ModelEvalRow['triage'] = null;
if (process.argv.includes('--skip-triage') === false) {
  const { cases } = loadTriageCases();
  const slots = Array.from({ length: concurrency }, () => [] as typeof cases);
  cases.forEach((c, i) => slots[i % concurrency]!.push(c));
  const results = await Promise.allSettled(
    slots.map((slot) =>
      runTriage(
        slot.map((c) => candidateOf(c)),
        {
          gateway,
          limit: 25,
          contextWindow,
          meta: { repoId: '0', prNumber: 0, initiator: 'model-eval' },
        },
      ),
    ),
  );
  const failed = results.filter((r) => r.status === 'rejected');
  if (failed.length > 0) {
    for (const f of failed)
      spec.errors.push({
        role: 'triage',
        caseId: '*',
        error: String((f as PromiseRejectedResult).reason),
      });
    spec.complete = false;
  } else {
    const proposals = results.flatMap(
      (r) => (r as PromiseFulfilledResult<Awaited<ReturnType<typeof runTriage>>>).value.proposals,
    );
    const t = scoreModel({
      model,
      ranAt: '',
      checklistVersion: TRIAGE_CHECKLIST_VERSION,
      cases,
      proposals,
    });
    triage = {
      total: t.total,
      agree: t.agree,
      disagree: t.disagree,
      abstained: t.abstained,
      rejected: t.rejected,
      agreement: t.agreement,
      missedReal: t.missedReal,
    };
  }
}

const row: ModelEvalRow = {
  model,
  engine: `OpenAI-compatible endpoint at ${host.host}`,
  ranAt: new Date().toISOString(),
  temperature,
  seed,
  checklistVersions: spec.checklistVersions,
  complete: spec.complete,
  roles: spec.roles,
  triage,
  errors: spec.errors,
};

const next: ModelEvalFile = {
  schema: 1,
  rows: [...MODEL_EVAL_RESULTS.rows.filter((r) => r.model !== model), row].sort((a, b) =>
    a.model.localeCompare(b.model),
  ),
};
writeFileSync(
  RESULTS_FILE,
  `// GENERATED by packages/security/src/eval/cli.ts — do not edit by hand.\nimport type { ModelEvalFile } from './types.js';\n\nexport const MODEL_EVAL_RESULTS: ModelEvalFile = ${JSON.stringify(next, null, 2)};\n`,
);
writeFileSync(MD_FILE, renderModelEval(next));

console.log(
  JSON.stringify(
    {
      secs: Math.round((Date.now() - started) / 1000),
      model,
      complete: row.complete,
      roles: row.roles,
      triage,
    },
    null,
    1,
  ),
);
if (!row.complete) {
  console.error(`\nPROVIDER ERRORS — ${row.errors.length} case(s) were NOT scored:`);
  for (const e of row.errors) console.error(`  ${e.role}/${e.caseId}: ${e.error}`);
  process.exit(1);
}
