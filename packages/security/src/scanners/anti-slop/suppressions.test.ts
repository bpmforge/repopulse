import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  MIN_SUPPRESSION_HITS,
  prSuppressionFinding,
  scanSuppressions,
  SUPPRESSION_CEILING_PER_KLOC,
  suppressionDensity,
  type SuppressionKind,
} from './suppressions.js';

// Suppression density (W18-04). The rate is arithmetic; what can be wrong is
// the lexing — a directive quoted in a string or mentioned in prose counted as
// one — so most of these cases are near misses that must count ZERO.

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FIXTURES = path.resolve(HERE, '../../../fixtures/suppressions');

const fixture = (dir: 'triggering' | 'clean', name: string) => ({
  path: `src/${name}`,
  source: readFileSync(path.join(FIXTURES, dir, name), 'utf8'),
});

const kinds = (name: string): SuppressionKind[] => {
  const { path: p, source } = fixture('triggering', name);
  return (scanSuppressions(p, source)?.hits ?? []).map((h) => h.kind);
};

describe('what counts as a suppression, per language', () => {
  it('TypeScript: explicit any, bare directives, file-wide disables', () => {
    expect(kinds('typed.ts')).toEqual([
      'eslint-disable-file',
      'ts-nocheck',
      'any-annotation',
      'as-any',
      'any-type-argument',
      'ts-ignore',
      'ts-expect-error-no-reason',
      'eslint-disable-line-no-rule',
      // `-- text` is a description, not a rule: still names no rule.
      'eslint-disable-line-no-rule',
      'biome-ignore-no-reason',
      'any-type-argument',
    ]);
  });

  it('Python: type: ignore without a code, bare noqa, pylint disable=all', () => {
    expect(kinds('legacy.py')).toEqual([
      'noqa-bare',
      'noqa-bare',
      'type-ignore-no-code',
      'pylint-disable-all',
      'type-ignore-no-code',
      // `# noqa: E501  # type: ignore` — the second segment is its own directive.
      'type-ignore-no-code',
    ]);
  });

  it('Go: //nolint naming no linter, or naming all of them', () => {
    expect(kinds('server.go')).toEqual(['nolint-bare', 'nolint-bare', 'nolint-bare']);
  });

  it('Rust: crate-level allow', () => {
    expect(kinds('lib.rs')).toEqual(['crate-allow', 'crate-allow']);
  });

  it('C/C++: MSVC and GCC/clang warning pragmas', () => {
    expect(kinds('native.c')).toEqual([
      'pragma-disable-warning',
      'pragma-disable-warning',
      'pragma-disable-warning',
    ]);
  });

  it('Java: @SuppressWarnings("all"), alone or in a list', () => {
    expect(kinds('Legacy.java')).toEqual([
      'suppress-warnings-all',
      'suppress-warnings-all',
      'suppress-warnings-all',
    ]);
  });

  it('reports the line of each hit', () => {
    const { path: p, source } = fixture('triggering', 'typed.ts');
    expect(scanSuppressions(p, source)?.hits.find((h) => h.kind === 'ts-ignore')?.line).toBe(8);
  });
});

describe('near misses count zero', () => {
  // Strings, regex literals, docstrings, prose comments, directives with a
  // reason or a rule name, item-level allows, push/pop pragmas, and a quoted
  // annotation inside a Java text block.
  for (const name of readdirSync(path.join(FIXTURES, 'clean'))) {
    it(name, () => {
      const { path: p, source } = fixture('clean', name);
      const scan = scanSuppressions(p, source);
      expect(scan, name).not.toBeNull();
      expect(scan?.hits, name).toEqual([]);
    });
  }

  it('THIS rule source, whose comments are full of directive names', () => {
    // The markers live in comments, so the rule's own explanation of them is
    // the nearest miss there is.
    const source = readFileSync(path.join(HERE, 'suppressions.ts'), 'utf8');
    expect(scanSuppressions('src/suppressions.ts', source)?.hits).toEqual([]);
  });

  it('skips generated, test and vendored files, and languages it does not read', () => {
    const bad = 'export const x = 1 as any;\n';
    expect(scanSuppressions('src/routeTree.gen.ts', bad)).toBeNull();
    expect(scanSuppressions('src/api.ts', `// @generated by protoc\n${bad}`)).toBeNull();
    expect(scanSuppressions('src/api.test.ts', bad)).toBeNull();
    expect(scanSuppressions('tests/api.ts', bad)).toBeNull();
    expect(scanSuppressions('pkg/_vendor/x.py', 'import a  # noqa\n')).toBeNull();
    expect(scanSuppressions('src/x_test.go', '//nolint\n')).toBeNull();
    expect(scanSuppressions('README.md', bad)).toBeNull();
  });

  it('does not count `any` in a declaration file', () => {
    // Where an untyped library gets its types; `any` there is often honest.
    expect(scanSuppressions('types/lib.d.ts', 'export declare const x: any;')?.hits).toEqual([]);
  });

  it('counts code lines, not comments or blanks', () => {
    const scan = scanSuppressions('src/a.py', '# header\n\nx = 1\n"""doc"""\n');
    expect(scan?.codeLines).toBe(2);
  });
});

/** A TypeScript file of `lines` code lines, `hits` of them carrying `as any`. */
const tsFile = (file: string, lines: number, hits: number) => ({
  path: file,
  source: Array.from({ length: lines }, (_, i) =>
    i < hits ? `const v${i} = load(${i}) as any;` : `const v${i} = load(${i});`,
  ).join('\n'),
});

describe('density and outliers', () => {
  it('a repository over the ceiling gets ONE finding carrying the counts by kind', () => {
    const result = suppressionDensity([tsFile('src/a.ts', 400, 16), tsFile('src/b.ts', 400, 16)]);
    expect(result.perKloc).toBe(40);
    const repo = result.findings.filter((f) => f.file === null);
    expect(repo).toHaveLength(1);
    expect(repo[0]).toMatchObject({ hits: 32, codeLines: 800, counts: { 'as-any': 32 } });
    expect(repo[0]?.message).toContain('as-any 32');
    // Both files sit AT the repository's rate: nothing stands out, so no file finding.
    expect(result.findings.filter((f) => f.file !== null)).toEqual([]);
  });

  it('at the ceiling is not over it', () => {
    const atCeiling = SUPPRESSION_CEILING_PER_KLOC; // per 1000 lines
    expect(suppressionDensity([tsFile('src/a.ts', 1000, atCeiling)]).findings).toEqual([]);
  });

  it('a clean repository with one dense file reports only that file', () => {
    const result = suppressionDensity([
      tsFile('src/dense.ts', 200, 12),
      ...Array.from({ length: 10 }, (_, i) => tsFile(`src/clean${i}.ts`, 500, 0)),
    ]);
    expect(result.findings).toHaveLength(1);
    expect(result.findings[0]).toMatchObject({ file: 'src/dense.ts', hits: 12, line: 1 });
  });

  it('a file must stand out from its repository, not merely clear the ceiling', () => {
    // Every file at 40/KLOC: the repository finding says it; ten file findings
    // saying the same thing would be noise.
    const files = Array.from({ length: 10 }, (_, i) => tsFile(`src/f${i}.ts`, 500, 20));
    const result = suppressionDensity(files);
    expect(result.findings.map((f) => f.file)).toEqual([null]);
  });

  it(`needs ${MIN_SUPPRESSION_HITS} hits: a tiny file is an anecdote`, () => {
    const result = suppressionDensity([tsFile('src/tiny.ts', 20, MIN_SUPPRESSION_HITS - 1)]);
    expect(result.findings).toEqual([]);
  });

  it('the ceiling is a parameter, so a workspace can tune it', () => {
    const files = [tsFile('src/a.ts', 1000, 15)];
    expect(suppressionDensity(files).findings).toEqual([]);
    expect(suppressionDensity(files, 10).findings).toHaveLength(1);
  });
});

describe('per pull request: what the diff ADDS', () => {
  const patch = (added: string[], context: string[] = []) =>
    [
      `@@ -10,${context.length + 1} +10,${context.length + added.length + 1} @@`,
      ' const keep = 1;',
      '-const removed = old as any;',
      ...context.map((l) => ` ${l}`),
      ...added.map((l) => `+${l}`),
    ].join('\n');

  it('counts suppressions on added lines only, at their new-side line numbers', () => {
    const added = [
      'const a = x as any;',
      '// @ts-ignore',
      'const b = y;',
      'const c: any = z;',
      '// eslint-disable-next-line',
      'const d = w as any;',
    ];
    const found = prSuppressionFinding([
      { path: 'src/a.ts', patch: patch(added, ['const old = q as any;']) },
    ]);
    expect(found).toMatchObject({ hits: 5, codeLines: 4, firstFile: 'src/a.ts' });
    // The context line's `as any` is not new and the removed line is gone.
    expect(found?.counts).toEqual({
      'as-any': 2,
      'ts-ignore': 1,
      'any-annotation': 1,
      'eslint-disable-line-no-rule': 1,
    });
    expect(found?.message).toContain('src/a.ts:12');
  });

  it('stays quiet below the hit floor or under the ceiling', () => {
    const few = ['const a = x as any;', 'const b = y as any;'];
    expect(prSuppressionFinding([{ path: 'src/a.ts', patch: patch(few) }])).toBeNull();
    const diluted = [
      ...Array.from({ length: 5 }, (_, i) => `const a${i} = x as any;`),
      ...Array.from({ length: 400 }, (_, i) => `const b${i} = ${i};`),
    ];
    expect(prSuppressionFinding([{ path: 'src/a.ts', patch: patch(diluted) }])).toBeNull();
  });

  it('ignores generated and test files and files with no patch', () => {
    const lines = Array.from({ length: 6 }, (_, i) => `const a${i} = x as any;`);
    expect(
      prSuppressionFinding([
        { path: 'src/a.test.ts', patch: patch(lines) },
        { path: 'src/routes.gen.ts', patch: patch(lines) },
        { path: 'src/big.ts', patch: null },
      ]),
    ).toBeNull();
  });
});
