import { ErrorNote } from '../../components/index.js';
import { useApiMutation, queryKeyFor } from '../../api/useApiQuery.js';
import {
  planScopeLabel,
  type GenerateRequest,
  type GenerateResult,
  type RepoNames,
} from './contracts.js';

// Generate a plan for exactly one scope (W17-24).
//
// The button SAYS what it will generate — the window and the repositories —
// and the line under it says what the server did: created a plan, or found
// that an identical one already existed and handed that back. The scope in
// that line comes from the server's answer, not from the props, so the two
// cannot disagree. A second press while the first is in flight is dropped
// here as well as serialised on the server; nothing is generated by mounting.

const LIST = { endpoint: '/plans' } as const;

export interface GeneratePlanButtonProps {
  window: string;
  repoIds: readonly number[];
  repoNames?: RepoNames | undefined;
}

export function GeneratePlanButton({ window, repoIds, repoNames }: GeneratePlanButtonProps) {
  const generate = useApiMutation<GenerateRequest, GenerateResult>(
    { endpoint: '/plans', method: 'POST' },
    { invalidate: [queryKeyFor(LIST)] },
  );
  const scope = planScopeLabel(repoIds, repoNames);
  const result = generate.data;

  return (
    <div className="flex flex-col items-end gap-1">
      <button
        type="button"
        className="rounded-md border border-accent bg-accent/10 px-3 py-1.5 text-sm disabled:opacity-50 focus-visible:outline focus-visible:outline-2 focus-visible:outline-accent"
        data-testid="generate-plan"
        disabled={generate.isPending}
        aria-busy={generate.isPending || undefined}
        onClick={() => {
          if (generate.isPending) return;
          generate.mutate({ window, repo_ids: [...new Set(repoIds)].sort((a, b) => a - b) });
        }}
      >
        {generate.isPending ? 'Generating…' : `Generate ${window} plan for ${scope}`}
      </button>
      {result && (
        <p className="text-xs text-fg-muted" data-testid="generate-plan-result" role="status">
          {result.reused
            ? `Nothing changed — the ${result.window} plan for ${planScopeLabel(result.repo_ids, repoNames)} (#${result.id}) already has these ${result.item_count} items.`
            : `Plan #${result.id} created for ${planScopeLabel(result.repo_ids, repoNames)}: ${result.item_count} items.`}
        </p>
      )}
      <ErrorNote error={generate.error} testId="generate-plan-error" />
    </div>
  );
}
