import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClientProvider } from '@tanstack/react-query';
import { createRouter, RouterProvider } from '@tanstack/react-router';
import { createQueryClient } from './api/queryClient.js';
import { NotFound } from './components/shell/NotFound.js';
import { AppError, reloadForNewVersion } from './components/shell/AppError.js';
import { routeTree } from './routeTree.gen';
import './styles/theme.css';

// App bootstrap. W4-03 migrated the W4-02 code-based bootstrap to FILE-BASED
// routing, which docs/TECH_STACK.md records as brief-fixed: routes live in
// src/routes/**, routeTree.gen.ts is generated by @tanstack/router-plugin and
// committed, never hand-edited.
//
// Router type is intentionally NOT registered globally, so rail links to
// not-yet-built routes stay loosely typed and resolve to the not-found
// placeholder instead of failing to compile.

const queryClient = createQueryClient();

// W20-17 (UX_TODO INS-57): a chunk from the previous release failed to load
// (the tab outlived an upgrade). Vite announces it; reload once to fetch the
// new version. If that already happened a moment ago, AppError explains.
window.addEventListener('vite:preloadError', (event) => {
  if (reloadForNewVersion()) event.preventDefault();
});

const router = createRouter({
  routeTree,
  context: { queryClient },
  defaultNotFoundComponent: NotFound,
  defaultErrorComponent: AppError,
});

const rootElement = document.getElementById('root');
if (!rootElement) {
  throw new Error('root element not found');
}

createRoot(rootElement).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <RouterProvider router={router} />
    </QueryClientProvider>
  </StrictMode>,
);
